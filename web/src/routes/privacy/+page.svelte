<h1>Privacy policy</h1>
<p class="meta">Last updated: November 1, 2026</p>

<p>This policy explains what Smart Edit (“the app”, “we”) does with your information. In short: your files stay on your device, and the data that does leave it is limited to your account details, basic usage statistics and the information needed to show ads.</p>

<h2>1. Who we are</h2>
<p>Smart Edit is developed by Vextech. Questions or requests: <strong>[add contact email]</strong>.</p>

<h2>2. Your files stay on your device</h2>
<p>Documents, photos, scans, PDFs and recognized text that you open in Smart Edit are processed on your device. The app does not upload them to our servers. If you share a file from the app, it goes to the app or person you choose.</p>

<h2>3. Information we collect</h2>
<ul>
<li><strong>Account details.</strong> If you create an account, we process your email address, a display name you choose and a unique account ID. This is handled by Google Firebase Authentication, and your profile is stored in Google Firebase.</li>
<li><strong>Usage and device information.</strong> We use Firebase Analytics to understand how the app is used. It collects things like which features are used, app version, device model, operating system, language, approximate region and an app-instance identifier. It does not include the contents of your files.</li>
<li><strong>Advertising information.</strong> The app shows ads through Unity Ads. To serve and measure ads, Unity and its partners may process your device’s advertising ID, IP address, device details and how you interact with ads.</li>
</ul>

<h2>4. Permissions the app asks for</h2>
<ul>
<li><strong>Camera</strong>: to scan documents and take pictures inside the app.</li>
<li><strong>Notifications</strong>: to tell you when a long task finishes.</li>
<li><strong>Internet</strong>: for sign-in, analytics and ads.</li>
<li><strong>Advertising ID</strong>: for ads, as described above. You can reset or delete it in your Android settings (Settings → Privacy → Ads).</li>
</ul>

<h2>5. How we use information</h2>
<p>To run your account, to keep the app working and improve it, and to show ads that keep the app free. We do not sell your account details or your files.</p>

<h2>6. Who we share it with</h2>
<p>Only with service providers that make the app work: Google (Firebase Authentication, Firebase Analytics and database hosting) and Unity (advertising). They process data under their own policies: <a href="https://firebase.google.com/support/privacy">Firebase privacy information</a> and <a href="https://unity.com/legal/privacy-policy">Unity privacy policy</a>. These providers may process data in countries other than yours.</p>

<h2>7. Keeping and deleting your data</h2>
<p>Account data is kept until you delete your account. You can delete it inside the app or on our <a href="/delete-account">account deletion page</a>. Files on your device are yours and are removed when you delete them or uninstall the app.</p>

<h2>8. Your choices and rights</h2>
<p>Depending on where you live, you may have the right to access, correct, export or delete your information, or to object to some processing. Use the contact address above and we will respond. You can also limit ad personalization in your Android settings.</p>

<h2>9. Children</h2>
<p>Smart Edit is not directed to children under 13, and we do not knowingly collect their personal information. If you believe a child has given us information, contact us and we will delete it.</p>

<h2>10. Security</h2>
<p>Account data is stored with Google Firebase and protected by access rules so that only you can read your own profile. No method of storage or transfer is perfectly secure, but we take reasonable care.</p>

<h2>11. This website</h2>
<p>The Smart Edit website is hosted on Google Firebase Hosting, which may keep standard server logs (such as IP address and the pages requested) for security and operation. The website does not use cookies or analytics. The free tools run entirely in your browser: the files you choose are processed on your device and are not uploaded.</p>

<h2>12. Changes</h2>
<p>If we change this policy, we will update the date above and, for significant changes, tell you in the app.</p>
<h2>Text recognition and third-party downloads</h2>
<p>The “Extract text” tool reads your images on your device. The first time you use it, your browser downloads the text engine and the data for your chosen language from a public content delivery network (jsDelivr and the Tesseract language-data host). Those requests reveal your IP address to that network, as any file download does, but your images and the text found in them are never sent anywhere.</p>
