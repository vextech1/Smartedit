<h1>Delete your account</h1>
<p class="meta">Smart Edit account deletion</p>

<h2>Delete it in the app</h2>
<ol>
<li>Open Smart Edit and sign in.</li>
<li>Go to <strong>Settings → Account</strong>.</li>
<li>Tap <strong>Delete account</strong> and confirm.</li>
</ol>
<p>Your account and profile are deleted straight away.</p>

<h2>Can’t open the app?</h2>
<p>Email us from the address you signed up with at <strong>[add contact email]</strong> with the subject “Delete my account”. We will delete the account and confirm by email, within 30 days.</p>

<h2>What gets deleted</h2>
<ul>
<li>Your sign-in (email address and account ID).</li>
<li>Your profile details, such as your display name.</li>
</ul>

<h2>What is not affected</h2>
<ul>
<li>Files on your device. They never left it, so you manage them yourself or by uninstalling the app.</li>
<li>Anonymous usage statistics already collected, which are not linked to your name or email.</li>
</ul>
<p>More detail is in our <a href="/privacy">privacy policy</a>.</p>
