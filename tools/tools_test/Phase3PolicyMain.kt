import com.vextech.smart_edit.core.library.*

private var checks = 0
private fun check(name: String, ok: Boolean) { checks++; if (!ok) throw AssertionError("FAILED: $name") }
private fun <T> eq(name: String, actual: T, expected: T) { checks++; if (actual != expected) throw AssertionError("FAILED: $name\n  expected: $expected\n  actual:   $actual") }

fun main() {
    // ---------- file actions
    eq("pdf actions", FileActionPolicies.actionsFor("a.pdf", "application/pdf", false), listOf(FileAction.EDIT_PDF, FileAction.CONVERT, FileAction.COMPRESS))
    eq("image actions", FileActionPolicies.actionsFor("a.JPG", "image/jpeg", false),
        listOf(FileAction.EDIT_IMAGE, FileAction.EXTRACT_TEXT, FileAction.CONVERT, FileAction.COMPRESS))
    eq("folder has none", FileActionPolicies.actionsFor("Docs", "inode/directory", true), emptyList())
    eq("docx has none", FileActionPolicies.actionsFor("a.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", false), emptyList())
    eq("octet-stream pdf by extension", FileActionPolicies.kindOf("scan.pdf", "application/octet-stream"), FileKind.PDF)
    eq("octet-stream png by extension", FileActionPolicies.kindOf("x.png", "application/octet-stream"), FileKind.IMAGE)
    eq("image by mime without extension", FileActionPolicies.kindOf("photo", "image/webp"), FileKind.IMAGE)
    eq("svg is not supported", FileActionPolicies.kindOf("logo.svg", "image/svg+xml"), FileKind.OTHER)
    eq("gif is not supported", FileActionPolicies.kindOf("a.gif", "image/gif"), FileKind.OTHER)
    eq("uppercase extension", FileActionPolicies.kindOf("A.PDF", ""), FileKind.PDF)
    eq("folder named like pdf has none", FileActionPolicies.actionsFor("x.pdf", "application/pdf", true), emptyList())

    // ---------- compression
    eq("kind pdf", CompressionPolicies.kindOf("a.pdf", "application/pdf"), CompressionKind.PDF)
    eq("kind image", CompressionPolicies.kindOf("a.png", "image/png"), CompressionKind.IMAGE)
    eq("kind other", CompressionPolicies.kindOf("a.zip", "application/zip"), CompressionKind.UNSUPPORTED)
    check("presets order quality", CompressionPreset.HIGH.quality > CompressionPreset.BALANCED.quality && CompressionPreset.BALANCED.quality > CompressionPreset.SMALLER.quality)
    for (kind in listOf("image", "embedded")) {
        val p = CompressionPreset.entries.map { if (kind == "image") CompressionPolicies.imageParams(it) else CompressionPolicies.embeddedImageParams(it) }
        check("$kind quality strictly decreases", p[0].jpegQuality > p[1].jpegQuality && p[1].jpegQuality > p[2].jpegQuality)
        check("$kind dimension strictly decreases", p[0].maxDimension > p[1].maxDimension && p[1].maxDimension > p[2].maxDimension)
    }
    val r = CompressionPreset.entries.map { CompressionPolicies.rasterParams(it) }
    check("raster dpi decreases", r[0].dpi > r[1].dpi && r[1].dpi > r[2].dpi)
    check("raster quality decreases", r[0].jpegQuality > r[1].jpegQuality && r[1].jpegQuality > r[2].jpegQuality)
    eq("scaled keeps small image", CompressionPolicies.scaledSize(800, 600, 1600), 800 to 600)
    eq("scaled exact limit", CompressionPolicies.scaledSize(1600, 900, 1600), 1600 to 900)
    eq("scaled landscape", CompressionPolicies.scaledSize(4000, 3000, 2000), 2000 to 1500)
    eq("scaled portrait", CompressionPolicies.scaledSize(3000, 4000, 2000), 1500 to 2000)
    eq("scaled extreme ratio never zero", CompressionPolicies.scaledSize(10000, 1, 100), 100 to 1)
    eq("scaled unlimited", CompressionPolicies.scaledSize(9000, 9000, 0), 9000 to 9000)
    try { CompressionPolicies.scaledSize(0, 10, 100); check("zero width rejected", false) } catch (_: IllegalArgumentException) { check("zero width rejected", true) }
    eq("percent half", CompressionPolicies.percentSaved(1000, 500), 50)
    eq("percent floors", CompressionPolicies.percentSaved(1000, 666), 33)
    eq("percent larger is negative", CompressionPolicies.percentSaved(1000, 1500), -50)
    eq("percent clamps", CompressionPolicies.percentSaved(100, 100000), -100)
    eq("percent zero original", CompressionPolicies.percentSaved(0, 10), 0)
    eq("verdict smaller", CompressionPolicies.verdict(1000, 800), CompressionVerdict.SMALLER)
    eq("verdict unchanged under threshold", CompressionPolicies.verdict(1000, 990), CompressionVerdict.UNCHANGED)
    eq("verdict unchanged equal", CompressionPolicies.verdict(1000, 1000), CompressionVerdict.UNCHANGED)
    eq("verdict larger", CompressionPolicies.verdict(1000, 1001), CompressionVerdict.LARGER)
    eq("verdict exactly threshold", CompressionPolicies.verdict(1000, 980), CompressionVerdict.SMALLER)
    eq("alpha stays png", CompressionPolicies.imageOutput(true), ImageOutput.PNG)
    eq("opaque becomes jpeg", CompressionPolicies.imageOutput(false), ImageOutput.JPEG)
    eq("output name", CompressionPolicies.outputName("report.final.pdf", "pdf"), "report.final_compressed.pdf")
    eq("output name png to jpg", CompressionPolicies.outputName("shot.png", "jpg"), "shot_compressed.jpg")
    eq("output name no extension", CompressionPolicies.outputName("notes", "pdf"), "notes_compressed.pdf")
    eq("output name blank", CompressionPolicies.outputName("  .pdf", "pdf"), "file_compressed.pdf")
    check("skip soft mask", CompressionPolicies.shouldSkipEmbeddedImage(2000, 2000, 500_000, true, false))
    check("skip stencil", CompressionPolicies.shouldSkipEmbeddedImage(2000, 2000, 500_000, false, true))
    check("skip tiny pixels", CompressionPolicies.shouldSkipEmbeddedImage(100, 100, 500_000, false, false))
    check("skip small stream", CompressionPolicies.shouldSkipEmbeddedImage(2000, 2000, 10_000, false, false))
    check("process large photo", !CompressionPolicies.shouldSkipEmbeddedImage(2000, 2000, 500_000, false, false))

    // ---------- OCR
    eq("clean line endings and blanks", OcrPolicies.clean("a  \r\n\r\n\r\n\r\nb\r"), "a\n\nb")
    eq("clean trims", OcrPolicies.clean("\n  hello \n"), "hello")
    eq("stats", OcrPolicies.stats("one two\n\nthree"), OcrStats(3, 11, 2))
    eq("stats empty", OcrPolicies.stats("  \n "), OcrStats(0, 0, 0))
    eq("title first line", OcrPolicies.suggestedTitle("\n\n Invoice 42 \nrest"), "Invoice 42")
    check("title cut at word", OcrPolicies.suggestedTitle("word ".repeat(30), 20).let { it.endsWith("…") && it.length <= 21 })
    eq("title empty", OcrPolicies.suggestedTitle("  \n"), "")
    eq("file name sanitized", OcrPolicies.textFileName("a/b:c*?", "20260101"), "a b c.txt")
    eq("file name fallback", OcrPolicies.textFileName("///", "20260101"), "ocr_20260101.txt")
    eq("file name trailing dots", OcrPolicies.textFileName("Report...", "x"), "Report.txt")
    check("file name length", OcrPolicies.textFileName("x".repeat(200), "x").length <= 64)
    eq("script zh", OcrPolicies.scriptForLanguage("zh-Hans"), OcrScript.CHINESE)
    eq("script ja", OcrPolicies.scriptForLanguage("ja"), OcrScript.JAPANESE)
    eq("script ko", OcrPolicies.scriptForLanguage("KO"), OcrScript.KOREAN)
    eq("script hi", OcrPolicies.scriptForLanguage("hi"), OcrScript.DEVANAGARI)
    eq("script default", OcrPolicies.scriptForLanguage("de"), OcrScript.LATIN)
    eq("script null", OcrPolicies.scriptForLanguage(null), OcrScript.LATIN)
    eq("retry suggested", OcrPolicies.suggestedRetry(OcrScript.LATIN, "ja"), OcrScript.JAPANESE)
    eq("no retry when matching", OcrPolicies.suggestedRetry(OcrScript.JAPANESE, "ja"), null)
    eq("no retry without language", OcrPolicies.suggestedRetry(OcrScript.LATIN, null), null)

    // ---------- crop
    eq("crop clamps and pushes right edge", CropRect.of(0.9f, 0.1f, 0.5f, 0.9f).let { it.right >= it.left + CropRect.MIN_SIZE - 0.0001f }, true)
    eq("crop within bounds", CropRect.of(-1f, -1f, 2f, 2f), CropRect.FULL)
    check("full is full", CropRect.FULL.isFull)
    check("partial is not full", !CropRect.of(0.1f, 0f, 1f, 1f).isFull)
    eq("crop pixels", CropRect(0.25f, 0.25f, 0.75f, 0.75f).toPixels(200, 100), IntRect(50, 25, 100, 50))
    val tiny = CropRect.of(0.5f, 0.5f, 0.5f, 0.5f).toPixels(100, 100)
    check("crop never empty", tiny.width >= 1 && tiny.height >= 1)
    val edge = CropRect(0.999f, 0.999f, 1f, 1f).toPixels(10, 10)
    check("crop stays inside image", edge.left + edge.width <= 10 && edge.top + edge.height <= 10 && edge.width >= 1)

    // ---------- edit stack
    var s = EditStack()
    check("empty stack", s.isEmpty && !s.canUndo && !s.canRedo)
    s = s.push(EditOp.Rotate(1)).push(EditOp.Rotate(1))
    eq("rotations merge", s.done, listOf(EditOp.Rotate(2)))
    s = s.push(EditOp.Rotate(2))
    check("rotation cancels out", s.isEmpty)
    s = s.push(EditOp.Rotate(-1))
    eq("negative rotation normalized", s.done, listOf(EditOp.Rotate(3)))
    eq("zero rotation ignored", s.push(EditOp.Rotate(4)).done, s.done)
    eq("full crop ignored", s.push(EditOp.Crop(CropRect.FULL)).done, s.done)
    eq("identity adjust ignored", s.push(EditOp.Adjust(AdjustParams())).done, s.done)
    var a = EditStack().push(EditOp.Adjust(AdjustParams(brightness = 20f))).push(EditOp.Adjust(AdjustParams(brightness = 40f)))
    eq("adjust replaces previous", a.done, listOf(EditOp.Adjust(AdjustParams(brightness = 40f))))
    a = a.push(EditOp.Adjust(AdjustParams()))
    check("identity adjust removes previous", a.isEmpty)
    eq("adjust clamps", EditStack().push(EditOp.Adjust(AdjustParams(brightness = 999f, contrast = 9f, saturation = -1f))).currentAdjust(), AdjustParams(100f, 2f, 0f))
    var f = EditStack().push(EditOp.Filter(ImageFilter.GRAYSCALE))
    eq("filter replaces filter", f.push(EditOp.Filter(ImageFilter.BLACK_WHITE)).done, listOf(EditOp.Filter(ImageFilter.BLACK_WHITE)))
    eq("same filter ignored", f.push(EditOp.Filter(ImageFilter.GRAYSCALE)).done, f.done)
    check("filter none removes filter", f.push(EditOp.Filter(ImageFilter.NONE)).isEmpty)
    check("filter none on empty ignored", EditStack().push(EditOp.Filter(ImageFilter.NONE)).isEmpty)
    eq("current filter", f.currentFilter(), ImageFilter.GRAYSCALE)
    eq("default filter", EditStack().currentFilter(), ImageFilter.NONE)
    eq("remove background once", EditStack().push(EditOp.RemoveBackground).push(EditOp.RemoveBackground).done, listOf(EditOp.RemoveBackground))
    // undo / redo
    var u = EditStack().push(EditOp.Rotate(1)).push(EditOp.Crop(CropRect(0.1f, 0.1f, 0.9f, 0.9f))).push(EditOp.RemoveBackground)
    eq("three ops", u.done.size, 3)
    u = u.undo()
    eq("undo removes last", u.done.size, 2); check("redo available", u.canRedo)
    u = u.undo().undo()
    check("fully undone", u.isEmpty && u.canRedo && !u.canUndo)
    check("undo on empty is safe", u.undo().isEmpty)
    u = u.redo().redo().redo()
    eq("redo restores all", u.done.size, 3); check("redo exhausted", !u.canRedo)
    check("redo when none is safe", u.redo().done.size == 3)
    var branch = EditStack().push(EditOp.Rotate(1)).push(EditOp.RemoveBackground).undo()
    check("redo before new edit", branch.canRedo)
    branch = branch.push(EditOp.Filter(ImageFilter.GRAYSCALE))
    check("new edit clears redo", !branch.canRedo)
    eq("branch content", branch.done, listOf(EditOp.Rotate(1), EditOp.Filter(ImageFilter.GRAYSCALE)))
    // undo of a merged rotation restores nothing of the intermediate state: it undoes the whole merged op
    val merged = EditStack().push(EditOp.Rotate(1)).push(EditOp.Rotate(1)).undo()
    check("undo merged rotation", merged.isEmpty)
    // sizes and output
    eq("rotated size odd", EditPolicies.rotatedSize(400, 300, 1), 300 to 400)
    eq("rotated size even", EditPolicies.rotatedSize(400, 300, 2), 400 to 300)
    eq("rotated size negative", EditPolicies.rotatedSize(400, 300, -1), 300 to 400)
    eq("output size pipeline", EditPolicies.outputSize(400, 200, listOf(EditOp.Rotate(1), EditOp.Crop(CropRect(0f, 0f, 1f, 0.5f)))), 200 to 200)
    eq("png after background removal", EditPolicies.outputFormat(false, listOf(EditOp.RemoveBackground)), ImageOutput.PNG)
    eq("png for alpha source", EditPolicies.outputFormat(true, emptyList()), ImageOutput.PNG)
    eq("jpeg otherwise", EditPolicies.outputFormat(false, listOf(EditOp.Rotate(1))), ImageOutput.JPEG)
    eq("edited name", EditPolicies.outputName("photo.png", ImageOutput.JPEG), "photo_edited.jpg")

    println("Phase 3 policy tests: PASS ($checks checks)")
}
